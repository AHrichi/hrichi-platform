#!/usr/bin/env node
// Regenerates the System Design search index of cheatsheet terms
// (libs/products/system-design/domain/src/lib/content/cheatsheets/terms.ts)
// from the sheets themselves: each section title and each table's or number
// list's first column, de-duplicated per sheet, in sheet order.
//
// The sheets stay lazy chunks in the app; this file is what search uses.
// The domain content spec checks it against `cheatTermsFrom`, so run this
// after editing a sheet:
//
//   node tools/scripts/system-design-cheat-terms.mjs && pnpm exec prettier --write libs/products/system-design/domain/src/lib/content/cheatsheets/terms.ts
//
// Needs Node 24 (it imports the .ts sheets with built-in type stripping).
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const dir = join(
  root,
  'libs/products/system-design/domain/src/lib/content/cheatsheets',
);
const MODULES = [
  'foundations',
  'scaling',
  'data',
  'communication',
  'reliability',
  'architecture',
  'security',
  'shipping',
  'case-studies',
];

/** Mirrors `cheatTermsFrom` in cheatsheets/index.ts. */
function termsOf(sheet) {
  const seen = new Set();
  const out = [];
  const push = (title) => {
    const trimmed = title?.trim();
    if (!trimmed) return;
    const key = trimmed.toLowerCase();
    if (seen.has(key)) return;
    seen.add(key);
    out.push({ module: sheet.module, title: trimmed });
  };
  for (const section of sheet.sections) {
    push(section.title);
    if (section.kind === 'numbers' || section.kind === 'table')
      for (const row of section.rows) push(row[0]);
  }
  return out;
}

const terms = [];
for (const module of MODULES) {
  const { cheatsheet } = await import(
    pathToFileURL(join(dir, `${module}.ts`)).href
  );
  terms.push(...termsOf(cheatsheet));
}

const body = terms
  .map((t) => `  { module: '${t.module}', title: ${JSON.stringify(t.title)} },`)
  .join('\n');
writeFileSync(
  join(dir, 'terms.ts'),
  `// Generated by tools/scripts/system-design-cheat-terms.mjs. Do not edit by hand.
import type { CheatTerm } from '../../engine/search';

export const CHEAT_TERMS: readonly CheatTerm[] = [
${body}
];
`,
);
console.log(`Wrote ${terms.length} cheatsheet terms.`);
