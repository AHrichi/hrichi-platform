// AutoSphere code-health metrics, for the before/after refactoring report
// (docs/autosphere/REFACTORING-REPORT.md). Prints Markdown to stdout.
//
// Usage: node tools/scripts/autosphere-metrics.mjs > docs/autosphere/metrics-<when>.md
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { gzipSync } from 'node:zlib';

const root = resolve(import.meta.dirname, '../..');
const roots = ['libs/products/autosphere', 'apps/products/autosphere'].map(
  (p) => join(root, p),
);
const skip = new Set(['node_modules', 'dist', 'cdk.out', '.angular']);

function walk(dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (skip.has(entry.name)) continue;
    const path = join(dir, entry.name);
    if (entry.isDirectory()) walk(path, out);
    else out.push(path);
  }
  return out;
}

const files = roots.flatMap((r) => walk(r));
const source = files.filter((f) => /\.(ts|html|scss|mjs)$/.test(f));
const lines = (f) => readFileSync(f, 'utf8').split('\n').length;
const rel = (f) => relative(root, f).replaceAll('\\', '/');

const sized = source
  .map((f) => ({ file: rel(f), lines: lines(f) }))
  .sort((a, b) => b.lines - a.lines);
const totalLines = sized.reduce((sum, f) => sum + f.lines, 0);
const components = source
  .filter((f) => f.endsWith('.ts'))
  .reduce(
    (n, f) => n + (readFileSync(f, 'utf8').match(/@Component\(/g) ?? []).length,
    0,
  );
const colourLiterals = source
  .filter((f) => f.endsWith('.scss'))
  .reduce(
    (n, f) =>
      n +
      (readFileSync(f, 'utf8').match(/#[0-9a-fA-F]{3,8}\b|rgba?\(/g) ?? [])
        .length,
    0,
  );
const specs = source.filter((f) => f.endsWith('.spec.ts')).length;
const stories = source.filter((f) => f.endsWith('.stories.ts')).length;

const e2eDirs = walk(join(root, 'apps')).filter(
  (f) => /-e2e[\\/]/.test(f) && f.endsWith('.spec.ts'),
);
const e2e = e2eDirs.filter((f) =>
  /autosphere/i.test(readFileSync(f, 'utf8')),
).length;

const models = walk(join(root, 'apps')).filter(
  (f) => f.endsWith('.glb') && /[\\/]public[\\/]/.test(f),
);

// JS a visitor downloads for AutoSphere: the chunks whose source mentions it,
// in whichever build exists (its own remote, else the shell).
function routeChunks() {
  for (const dist of [
    'dist/apps/products/autosphere/web/browser',
    'dist/apps/portfolio/shell/browser',
  ]) {
    const dir = join(root, dist);
    if (!existsSync(dir)) continue;
    const js = readdirSync(dir).filter((f) => f.endsWith('.js'));
    const hits = js.filter((f) =>
      /autosphere|AutoSphere/.test(readFileSync(join(dir, f), 'utf8')),
    );
    if (!hits.length) continue;
    const raw = hits.reduce((n, f) => n + statSync(join(dir, f)).size, 0);
    const gz = hits.reduce(
      (n, f) => n + gzipSync(readFileSync(join(dir, f))).length,
      0,
    );
    return { dist, count: hits.length, raw, gz };
  }
  return null;
}

const kb = (n) => `${(n / 1024).toFixed(1)} kB`;
const mb = (n) => `${(n / 1024 / 1024).toFixed(2)} MB`;
const chunks = routeChunks();

const out = [];
out.push(`# AutoSphere metrics (${new Date().toISOString().slice(0, 10)})`);
out.push('');
out.push(`Generated by \`node tools/scripts/autosphere-metrics.mjs\`.`);
out.push('');
out.push('| Metric | Value |');
out.push('| --- | --- |');
out.push(`| Source files (ts/html/scss/mjs) | ${sized.length} |`);
out.push(`| Source lines | ${totalLines} |`);
out.push(
  `| Largest file | ${sized[0] ? `\`${sized[0].file}\` (${sized[0].lines} lines)` : 'n/a'} |`,
);
out.push(
  `| Files over 300 lines | ${sized.filter((f) => f.lines > 300).length} |`,
);
out.push(`| \`@Component\` classes | ${components} |`);
out.push(`| Hex / rgb() literals in SCSS | ${colourLiterals} |`);
out.push(`| Unit spec files | ${specs} |`);
out.push(`| Storybook story files | ${stories} |`);
out.push(`| E2E spec files mentioning AutoSphere | ${e2e} |`);
for (const m of models) {
  out.push(`| 3D model \`${rel(m)}\` | ${mb(statSync(m).size)} |`);
}
out.push(
  `| JS chunks loaded for AutoSphere | ${
    chunks
      ? `${chunks.count} chunks, ${kb(chunks.raw)} raw / ${kb(chunks.gz)} gzip (from \`${chunks.dist}\`)`
      : 'n/a (no build in dist/)'
  } |`,
);
out.push('');
out.push('## Files over 300 lines');
out.push('');
out.push('| File | Lines |');
out.push('| --- | --- |');
for (const f of sized.filter((f) => f.lines > 300)) {
  out.push(`| \`${f.file}\` | ${f.lines} |`);
}
console.log(out.join('\n'));
