// Fetches LuxPath's catalogue photos from open-licence APIs and writes them,
// with their credits, to a lazy TypeScript module. Thumbnails ship inside the
// app (as data URIs) so the Materials screen works offline on site, inside
// the shell and standalone alike, with no image host to allow in the CSP.
//
// Source: the Wikimedia Commons API (https://commons.wikimedia.org/w/api.php),
// free and without a key; each photo keeps its author, licence and link.
//
// Usage: node tools/scripts/material-photos.mjs
import { writeFileSync } from 'node:fs';

const OUT =
  'libs/products/lighting/feature/src/lib/diagrams/material-art/material-photos.generated.ts';
const UA = {
  'User-Agent':
    'LuxPath/1.0 (https://github.com/AHrichi/hrichi-platform; build-time photo fetch)',
};
// Cards show a 4:3 crop; fitting 320 × 240 keeps the module small.
const WIDTH = 320;
const HEIGHT = 240;

/**
 * One photo per drawing kind, picked by hand from the API's search results.
 * No openly licensed photo shows an all-in-one solar street light well, so
 * that kind keeps its drawing. (Openverse was tried too, but its API timed
 * out and throttled too often to rebuild from.)
 */
const PICKS = {
  pole: 'File:20160207 xl P1020443-LED-Strassenlampen Landhausstrasse Strausberg Vorstadt.JPG',
  conic:
    'File:20160206 xl P1020432-LED-Strassenlampen Gustav-Kurtze-Wohnpark Strausberg Vorstadt.JPG',
  solarPole:
    'File:Solar power for streetlights along part of Paradise Trail (3937798321).jpg',
  luminaire:
    'File:Brooklands Road, Hall Green - new lamppost installation - new lamp (7949223938).jpg',
  panel: 'File:BP Solar 12V solar panel.jpg',
  battery: 'File:12V 200Ah lithium iron phosphate battery.jpg',
  bolts: 'File:AnchorBolt Moku 01.jpg',
  cable: 'File:3.core.cable.JPG',
  woodPole: 'File:ABC TQ3157 073.JPG',
  concretePole: 'File:9 Sichovykh Striltsiv Street, Bolekhiv (2).jpg',
};

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
const strip = (html = '') =>
  html
    .replace(/<[^>]+>/g, '')
    .replace(/\s+/g, ' ')
    .trim();

async function fromCommons(title) {
  const url = new URL('https://commons.wikimedia.org/w/api.php');
  for (const [key, value] of Object.entries({
    action: 'query',
    format: 'json',
    titles: title,
    prop: 'imageinfo',
    iiprop: 'url|extmetadata',
    iiurlwidth: String(WIDTH),
    iiurlheight: String(HEIGHT),
  })) {
    url.searchParams.set(key, value);
  }
  const data = await (await fetch(url, { headers: UA })).json();
  const page = Object.values(data.query.pages)[0];
  const info = page.imageinfo[0];
  const meta = info.extmetadata;
  return {
    image: info.thumburl,
    title: strip(meta.ObjectName?.value) || title.replace(/^File:|\.\w+$/g, ''),
    author: strip(meta.Artist?.value) || 'Unknown',
    license: meta.LicenseShortName?.value ?? '',
    licenseUrl: meta.LicenseUrl?.value ?? '',
    source: info.descriptionurl,
  };
}

const photos = {};
for (const [kind, pick] of Object.entries(PICKS)) {
  const meta = await fromCommons(pick);
  const bytes = Buffer.from(
    await (await fetch(meta.image, { headers: UA })).arrayBuffer(),
  );
  const { image, ...credit } = meta;
  photos[kind] = {
    src: `data:image/jpeg;base64,${bytes.toString('base64')}`,
    ...credit,
  };
  console.log(
    `${kind}: ${Math.round(bytes.length / 1024)} kB, ${credit.license}`,
  );
  await sleep(2000);
}

writeFileSync(
  OUT,
  `// Generated by tools/scripts/material-photos.mjs: do not edit by hand.
// Photos from Wikimedia Commons, under the licences named below.
import type { ArtKind } from './material-art';

export interface MaterialPhoto {
  src: string;
  title: string;
  author: string;
  license: string;
  licenseUrl: string;
  source: string;
}

export const MATERIAL_PHOTOS: Partial<Record<ArtKind, MaterialPhoto>> = ${JSON.stringify(photos, null, 2)};
`,
);
console.log(`Wrote ${OUT}`);
