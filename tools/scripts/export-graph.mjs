// Exports this workspace's real Nx project graph for the constellation hero
// (ADR-0011): projects, their tags and dependencies, the federated remotes
// from tools/federation/remotes.json, and a deterministic 3D layout.
//
// The output is committed; CI reruns this script and fails on any diff, so
// the hero can never drift from the repository.
//
// Usage: node tools/scripts/export-graph.mjs
import { createProjectGraphAsync } from '@nx/devkit';
import { readFileSync, writeFileSync } from 'node:fs';

const output = 'libs/three/constellation/src/generated/graph.json';

// A running Nx daemon can serve a graph that misses recent imports, which
// made CI's export differ from the committed one; compute it fresh.
process.env.NX_DAEMON = 'false';
const graph = await createProjectGraphAsync({ exitOnError: true });
const names = Object.keys(graph.nodes).sort();
const index = new Map(names.map((name, i) => [name, i]));

const tag = (tags, axis) =>
  tags.find((t) => t.startsWith(`${axis}:`))?.slice(axis.length + 1) ?? null;

const nodes = names.map((name) => {
  const { type, data } = graph.nodes[name];
  const tags = data.tags ?? [];
  return {
    id: name,
    kind: type,
    // e2e projects carry no tags; they belong to the app they test.
    scope: tag(tags, 'scope') ?? 'test',
    layer: tag(tags, 'type') ?? type,
    runtime: tag(tags, 'runtime') ?? 'node',
  };
});

/** [source, target, kind]: kind is static, dynamic, implicit or federated. */
const edges = [];
for (const name of names) {
  for (const dependency of graph.dependencies[name] ?? []) {
    if (index.has(dependency.target)) {
      edges.push([
        index.get(name),
        index.get(dependency.target),
        dependency.type,
      ]);
    }
  }
}
// Remotes are loaded at runtime, so Nx doesn't see them: the shell loads
// every remote in the registry.
const registry = JSON.parse(
  readFileSync('tools/federation/remotes.json', 'utf8'),
);
for (const remote of Object.keys(registry)) {
  if (index.has('shell') && index.has(remote)) {
    edges.push([index.get('shell'), index.get(remote), 'federated']);
  }
}
edges.sort((a, b) => a[0] - b[0] || a[1] - b[1]);

layout(nodes, edges);

const result = {
  $comment:
    'Generated by tools/scripts/export-graph.mjs from the Nx project graph. Do not edit.',
  nodes,
  edges,
};
writeFileSync(output, `${JSON.stringify(result, null, 2)}\n`);
console.log(
  `Wrote ${output}: ${nodes.length} projects, ${edges.length} dependencies`,
);

/**
 * Seeded force-directed layout in 3D: nodes repel, dependencies pull, and
 * each scope is drawn towards its own anchor so products read as clusters.
 * Only arithmetic and Math.sqrt/sin/cos, so results match across machines;
 * coordinates are rounded to keep diffs small.
 */
function layout(nodes, edges) {
  const random = mulberry32(20261027);
  const scopes = [...new Set(nodes.map((n) => n.scope))].sort();
  // Scope anchors spread evenly on a sphere (golden-angle spiral).
  const anchors = new Map(
    scopes.map((scope, i) => {
      const y = 1 - (2 * (i + 0.5)) / scopes.length;
      const r = Math.sqrt(1 - y * y);
      const theta = i * Math.PI * (3 - Math.sqrt(5));
      return [
        scope,
        [Math.cos(theta) * r * 0.6, y * 0.45, Math.sin(theta) * r * 0.6],
      ];
    }),
  );
  const p = nodes.map((n) => {
    const [ax, ay, az] = anchors.get(n.scope);
    return [
      ax + (random() - 0.5) * 0.3,
      ay + (random() - 0.5) * 0.3,
      az + (random() - 0.5) * 0.3,
    ];
  });

  for (let step = 0; step < 600; step++) {
    const cooling = 1 - step / 600;
    const force = p.map(() => [0, 0, 0]);
    for (let i = 0; i < p.length; i++) {
      for (let j = i + 1; j < p.length; j++) {
        const d = sub(p[i], p[j]);
        const dist2 = Math.max(dot(d, d), 1e-4);
        const push = 0.012 / dist2;
        addScaled(force[i], d, push);
        addScaled(force[j], d, -push);
      }
    }
    for (const [a, b] of edges) {
      const d = sub(p[b], p[a]);
      const dist = Math.sqrt(dot(d, d)) || 1e-4;
      const pull = (dist - 0.5) * 0.06;
      addScaled(force[a], d, pull / dist);
      addScaled(force[b], d, -pull / dist);
    }
    nodes.forEach((n, i) => {
      addScaled(force[i], sub(anchors.get(n.scope), p[i]), 0.02);
      // A soft wall at radius 1: loosely linked projects (the API, the
      // e2e suite) can't drift off and squeeze everything else when scaled.
      const r = Math.sqrt(dot(p[i], p[i]));
      if (r > 1) {
        addScaled(force[i], p[i], (-(r - 1) * 0.6) / r);
      }
    });
    for (let i = 0; i < p.length; i++) {
      const length = Math.sqrt(dot(force[i], force[i]));
      const limit = 0.05 * cooling + 0.002;
      addScaled(p[i], force[i], length > limit ? limit / length : 1);
    }
  }

  // Centre on the origin and scale so the farthest node sits at radius 1.
  const centre = p
    .reduce(
      (sum, v) => [sum[0] + v[0], sum[1] + v[1], sum[2] + v[2]],
      [0, 0, 0],
    )
    .map((c) => c / p.length);
  const radius = Math.max(
    ...p.map((v) => Math.sqrt(dot(sub(v, centre), sub(v, centre)))),
  );
  nodes.forEach((n, i) => {
    const [x, y, z] = sub(p[i], centre).map((c) => c / radius);
    Object.assign(n, { x: round(x), y: round(y), z: round(z) });
  });
}

function sub(a, b) {
  return [a[0] - b[0], a[1] - b[1], a[2] - b[2]];
}
function dot(a, b) {
  return a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
}
function addScaled(target, v, s) {
  target[0] += v[0] * s;
  target[1] += v[1] * s;
  target[2] += v[2] * s;
}
function round(value) {
  return Math.round(value * 1000) / 1000 || 0;
}
function mulberry32(seed) {
  return () => {
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
