const WORD_TOKEN_REGEX = /[\p{L}\p{N}ʼ']+/gu;

export function buildStopwordSet(
  customStopwords: readonly string[] = [],
): Set<string> {
  const set = new Set<string>();
  for (const w of DEFAULT_MULTILINGUAL_STOPWORDS) {
    set.add(w.toLowerCase().trim());
  }
  for (const custom of customStopwords) {
    const normalized = custom.toLowerCase().trim();
    if (normalized) {
      set.add(normalized);
    }
  }
  return set;
}

/**
 * Extracts normalized lexical word tokens (length >= 3, non-numeric, non-stopword)
 * from a chat message body.
 */
export function tokenizeChatWords(
  text: string,
  stopwordSet: ReadonlySet<string>,
): string[] {
  // Strip URLs before tokenizing words
  const withoutUrls = text.replace(
    /https?:\/\/[^\s<>"]+|www\.[^\s<>"]+/gi,
    ' ',
  );
  const matches = withoutUrls.match(WORD_TOKEN_REGEX);
  if (!matches) {
    return [];
  }

  const tokens: string[] = [];
  for (const rawToken of matches) {
    const cleaned = rawToken
      .toLowerCase()
      .replace(/^[ʼ']+|[ʼ']+$/g, '')
      .replace(/'s$/g, '');

    if (cleaned.length < 3) {
      continue;
    }
    // Skip purely numeric tokens
    if (/^\d+$/.test(cleaned)) {
      continue;
    }
    if (stopwordSet.has(cleaned)) {
      continue;
    }
    tokens.push(cleaned);
  }

  return tokens;
}
