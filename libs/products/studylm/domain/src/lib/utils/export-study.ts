import type { StudyFlashcard } from '../models/flashcard.model';
import type { StudyOverview } from '../models/synthesis.model';
import type { StudyQuizQuestion } from '../models/quiz.model';

export function exportToAnkiCsv(flashcards: StudyFlashcard[]): string {
  const header = '#separator:Tab\n#html:true\n#tags column:3\n';
  const rows = flashcards.map((card) => {
    const front = card.front.replace(/\t/g, ' ').replace(/\n/g, '<br>');
    const back = `${card.back.replace(/\t/g, ' ').replace(/\n/g, '<br>')}<br><br><small><i>Citation: ${card.sourceCitation}</i></small>`;
    const tags = `StudyLM ${card.tier} ${card.category.replace(/\s+/g, '_')}`;
    return `${front}\t${back}\t${tags}`;
  });
  return header + rows.join('\n');
}

export function exportToMarkdown(
  subject: string,
  overview: StudyOverview | null,
  flashcards: StudyFlashcard[],
  quiz: StudyQuizQuestion[],
): string {
  let md = `# StudyLM Briefing & Drill: ${subject}\n\n`;
  md += `*Generated by StudyLM & n8n AI Engine*\n\n`;

  if (overview) {
    md += `## Executive Summary\n\n${overview.executiveSummary}\n\n`;
    md += `### Key Takeaways\n\n`;
    overview.keyTakeaways.forEach((k) => {
      md += `- ${k}\n`;
    });
    md += `\n`;
  }

  md += `## Flashcards Deck (${flashcards.length} Cards)\n\n`;
  const tiers = ['beginner', 'intermediate', 'expert'] as const;
  tiers.forEach((tier) => {
    const tierCards = flashcards.filter((c) => c.tier === tier);
    if (tierCards.length > 0) {
      md += `### ${tier.toUpperCase()} Tier\n\n`;
      tierCards.forEach((c, idx) => {
        md += `#### Card ${idx + 1}: ${c.category}\n`;
        md += `**Q:** ${c.front}\n\n`;
        md += `**A:** ${c.back}\n\n`;
        md += `*Citation: ${c.sourceCitation}*\n\n---\n\n`;
      });
    }
  });

  md += `## Interactive Quiz Bank (${quiz.length} Questions)\n\n`;
  tiers.forEach((tier) => {
    const tierQuestions = quiz.filter((q) => q.tier === tier);
    if (tierQuestions.length > 0) {
      md += `### ${tier.toUpperCase()} Tier\n\n`;
      tierQuestions.forEach((q, idx) => {
        md += `#### Question ${idx + 1}\n`;
        md += `${q.question}\n\n`;
        q.options.forEach((opt, optIdx) => {
          const letter = String.fromCharCode(65 + optIdx);
          const isCorrect = optIdx === q.correctIndex ? ' [CORRECT]' : '';
          md += `- **${letter}:** ${opt}${isCorrect}\n`;
        });
        md += `\n**Explanation:** ${q.explanation}\n`;
        md += `*Citation: ${q.sourceCitation}*\n\n---\n\n`;
      });
    }
  });

  return md;
}
